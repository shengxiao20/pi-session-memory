import assert from "node:assert/strict";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { FinalAssistantMessage as AssistantMessage } from "../src/memory-output.ts";

const home = mkdtempSync(join(tmpdir(), "pi-okf-output-"));
process.env.HOME = home; process.env.USERPROFILE = home;
const configRoot = join(home, ".pi", "agent", "pi-session-memory");
mkdirSync(configRoot, { recursive: true });
const configure = (extra = {}) => writeFileSync(join(configRoot, "config.json"), JSON.stringify({ recallLimit: 20, ...extra }));
configure();
const { MemoryOutput } = await import("../src/memory-output.ts");
const { resolveKnowledgePath } = await import("../src/knowledge-storage.ts");
const { writeMeetingMinutes } = await import("../src/meeting-minutes.ts");
const { getSessionMemoryConfig } = await import("../src/config.ts");
const conclusion = { description: "Joule research findings and deployment uncertainty", findings: "Research only.[^transcript-1]", decisions: "None", unverified_inferences: "Deployment is not confirmed.", disagreements: "None", open_questions: "Was it deployed?", actions: "Check the deployment evidence." };
const final = { role: "assistant", content: [{ type: "text", text: "A different summary" }], stopReason: "stop", timestamp: 1 } as AssistantMessage;
const turn = { turn_id: "pi:historical:abc", session_id: "pi:historical", turn_index: 7, source: "pi" as const, cwd: home, ts: 1, user_text: "Joule Engagement Layer", reply_text: "Research, not deployment.", score: 11 };
const defaultRoot = join(configRoot, "knowledge");
try {
  assert.equal(resolveKnowledgePath(), defaultRoot);
  configure({ enableDiscussion: true, consultation: { timeoutMs: 1000 } });
  assert.equal(getSessionMemoryConfig().consultation?.knowledgePath, undefined, "default storage must not require an explicit path");
  assert.equal(resolveKnowledgePath(), defaultRoot);
  const output = new MemoryOutput();
  assert.equal(output.finalize(final), final, "unrelated responses stay unchanged");
  assert.throws(() => output.save("question", conclusion, "main"), /No recalled or fetched/);
  output.addTranscript([turn, turn]);
  assert.deepEqual(output.sourceIds(), [{ id: "transcript-1", session_id: turn.session_id }]);
  const unsaved = output.finalize(final);
  assert.equal(unsaved.stopReason, "error");
  assert.deepEqual(unsaved.content, []);
  assert.match(unsaved.errorMessage!, /OKF conclusion was not saved/);
  const toolMessage = { ...final, content: [{ type: "toolCall", id: "call", name: "finish_memory_recall", arguments: {} }] } as AssistantMessage;
  assert.equal(output.finalize(toolMessage), toolMessage, "tool-call messages remain executable");
  assert.throws(() => output.save("question", { ...conclusion, actions: " " }, "main"), /actions must be non-empty/);
  const saved = output.save("Review Joule", conclusion, "main");
  assert.equal(saved.path, join(defaultRoot, "meetings", saved.meeting_id, "minutes.md"));
  assert.equal((output.finalize(final).content[0] as any).text, readFileSync(saved.path, "utf8"));
  assert.equal(saved.markdown, readFileSync(saved.path, "utf8"));
  assert.match(saved.markdown, /^---\ndescription: "Joule research findings and deployment uncertainty"\n---/);
  assert.doesNotMatch(saved.markdown, /okf_version:|evidence_route:|meeting_id:|generated:/);
  assert.match(saved.markdown, /\[\^transcript-1\]/);
  assert.equal(readdirSync(join(defaultRoot, "meetings", saved.meeting_id)).length, 2);
  assert.match(readFileSync(join(defaultRoot, "meetings", saved.meeting_id, "evidence-1.md"), "utf8"), /pi:historical:abc/);
  output.addTranscript([turn]);
  assert.equal(output.finalize(final).stopReason, "error", "new evidence invalidates a saved conclusion");
  output.startDiscussion();
  assert.throws(() => output.save("question", conclusion, "main"), /Finish or cancel/);
  output.cancelDiscussion();
  assert.equal(output.finalize(final).stopReason, "error", "cancelling Discussion does not discard independent fetch evidence");
  output.reset();
  assert.equal(output.finalize(final), final);
  output.addTranscript([]);
  const empty = output.save("No matches", { ...conclusion, findings: "None" }, "main");
  assert.match(empty.markdown, /# Sources\n\n\n/);
  assert.equal((output.finalize(final).content[0] as any).text, empty.markdown);

  const vault = join(home, "vault");
  mkdirSync(vault);
  configure({ obsidianExportEnabled: true, obsidianVaultPath: vault });
  assert.equal(resolveKnowledgePath(), vault);
  const defaultMeetingsBefore = readdirSync(join(defaultRoot, "meetings"));
  output.reset(); output.addTranscript([turn]);
  const vaultRecall = output.save("Review Joule", conclusion, "main");
  assert.equal(vaultRecall.path, join(vault, "meetings", vaultRecall.meeting_id, "minutes.md"));
  assert.equal((output.finalize(final).content[0] as any).text, readFileSync(vaultRecall.path, "utf8"));
  output.reset(); output.startDiscussion();
  const discussion = writeMeetingMinutes({ id: "discussion", owner: "main", question: "Review Joule", knowledgePath: resolveKnowledgePath(), timeoutMs: 1000,
    answers: [{ sessionId: turn.session_id, question: "Review Joule", answer: "Research only", messageIds: ["message"] }], evidence: [turn],
  }, { ...conclusion, findings: "Research only.[^consultation-1]" });
  output.complete(discussion.markdown);
  assert.equal(discussion.path, join(vault, "meetings", "discussion", "minutes.md"));
  assert.equal((output.finalize(final).content[0] as any).text, readFileSync(discussion.path, "utf8"));
  assert.match(discussion.markdown, /^---\ndescription: "Joule research findings and deployment uncertainty"\n---/);
  assert.deepEqual(readdirSync(join(defaultRoot, "meetings")), defaultMeetingsBefore, "Obsidian must replace default storage, not duplicate it");
  configure({ obsidianExportEnabled: true, obsidianVaultPath: join(home, "missing") });
  output.reset(); output.addTranscript([turn]);
  assert.throws(() => output.save("question", conclusion, "main"), /existing absolute vault/);
  assert.equal(output.finalize(final).stopReason, "error", "storage failure must not publish a success response");
  assert.ok(!existsSync(join(home, "missing")));
  assert.deepEqual(readdirSync(join(defaultRoot, "meetings")), defaultMeetingsBefore);
  configure({ obsidianExportEnabled: true, obsidianVaultPath: "relative-vault" });
  assert.throws(() => resolveKnowledgePath(), /existing absolute vault/);
  configure({ obsidianExportEnabled: true, obsidianVaultPath: join(configRoot, "config.json") });
  assert.throws(() => resolveKnowledgePath(), /existing absolute vault/);
  const aborted = { ...final, stopReason: "aborted" } as AssistantMessage;
  assert.equal(output.finalize(aborted), aborted);
  output.reset(); output.startDiscussion(); output.cancelDiscussion();
  assert.equal(output.finalize(final), final, "explicit cancellation without transcript work does not fabricate minutes");
  console.log("memory-output tests passed: exact OKF chat/file equality, both storage targets, strict errors and lifecycle isolation");
} finally { rmSync(home, { recursive: true, force: true }); }
