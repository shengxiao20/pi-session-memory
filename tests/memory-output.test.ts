import assert from "node:assert/strict";
import { knowledgeFields } from "./helpers/knowledge-fixture.ts";
import { readConceptMetadata } from "../src/knowledge/okf-frontmatter.ts";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { FinalAssistantMessage as AssistantMessage } from "../src/presentation/memory-output.ts";

const home = mkdtempSync(join(tmpdir(), "pi-okf-output-"));
process.env.HOME = home; process.env.USERPROFILE = home;
const configRoot = join(home, ".pi", "agent", "pi-session-memory");
mkdirSync(configRoot, { recursive: true });
const configure = (extra = {}) => writeFileSync(join(configRoot, "config.json"), JSON.stringify({ recallLimit: 20, ...extra }));
configure();
const { MemoryOutput } = await import("../src/presentation/memory-output.ts");
const { resolveKnowledgePath } = await import("../src/knowledge/knowledge-storage.ts");
const { writeMeetingMinutes } = await import("../src/knowledge/meeting-minutes.ts");
const { getSessionMemoryConfig } = await import("../src/settings/config.ts");
const conclusion = { ...knowledgeFields, description: "Joule research findings and deployment uncertainty", findings: "Research only.[^transcript-1]", decisions: "None", unverified_inferences: "Deployment is not confirmed.", disagreements: "None", open_questions: "Was it deployed?", actions: "Check the deployment evidence." };
const final = { role: "assistant", content: [{ type: "text", text: "A different summary" }], stopReason: "stop", timestamp: 1 } as AssistantMessage;
const turn = { turn_id: "pi:historical:abc", session_id: "pi:historical", turn_index: 7, source: "pi" as const, cwd: home, ts: 1, user_text: "Joule Engagement Layer", reply_text: "Research, not deployment.", score: 11 };
const defaultRoot = join(configRoot, "knowledge");
try {
  assert.equal(resolveKnowledgePath(), defaultRoot);
  configure({ recallMode: "discussion", consultation: { timeoutMs: 1000 } });
  assert.equal(getSessionMemoryConfig().knowledgePath, undefined, "default storage must not require an explicit path");
  assert.equal(resolveKnowledgePath(), defaultRoot);
  const output = new MemoryOutput();
  assert.equal(output.finalize(final), final, "unrelated responses stay unchanged");
  assert.throws(() => output.save("question", conclusion), /No recalled or fetched/);
  output.addTranscript([turn, turn]);
  assert.deepEqual(output.sourceIds(), [{ id: "transcript-1", session_id: turn.session_id }]);
  const unsaved = output.finalize(final);
  assert.equal(unsaved.stopReason, "error");
  assert.deepEqual(unsaved.content, []);
  assert.match(unsaved.errorMessage!, /OKF conclusion was not saved/);
  const toolMessage = { ...final, content: [{ type: "toolCall", id: "call", name: "finish_memory_recall", arguments: {} }] } as AssistantMessage;
  assert.equal(output.finalize(toolMessage), toolMessage, "tool-call messages remain executable");
  assert.throws(() => output.save("question", { ...conclusion, actions: " " }), /actions must be non-empty/);
  const saved = output.save("Review Joule", conclusion);
  assert.equal(saved.path, join(defaultRoot, "meetings", conclusion.topic_path, saved.meeting_id, "minutes.md"));
  assert.equal((output.finalize(final).content[0] as any).text, readFileSync(saved.path, "utf8"));
  assert.equal(saved.markdown, readFileSync(saved.path, "utf8"));
  const metadata = readConceptMetadata(saved.markdown, saved.path);
  assert.equal(metadata.type, "Meeting Minutes");
  assert.equal(metadata.description, conclusion.description);
  assert.equal(metadata.status, "draft");
  assert.match((metadata.generated as any).by, /^pi-session-memory\//);
  assert.deepEqual(metadata.sources, [{ id: "transcript-1", resource: "./evidence-1.md", title: `Transcript evidence from ${turn.session_id}` }]);
  assert.doesNotMatch(saved.markdown, /okf_version:|evidence_route:|meeting_id:|verified:/);
  assert.equal(saved.concept_id, `meetings/${conclusion.topic_path}/${saved.meeting_id}/minutes`);
  assert.match(saved.markdown, /\[\^transcript-1\]/);
  assert.equal(readdirSync(join(defaultRoot, "meetings", conclusion.topic_path, saved.meeting_id)).length, 3);
  const evidenceMarkdown = readFileSync(join(defaultRoot, "meetings", conclusion.topic_path, saved.meeting_id, "evidence-1.md"), "utf8");
  assert.match(evidenceMarkdown, /pi:historical:abc/);
  for (const text of [turn.user_text, turn.reply_text]) assert.equal(evidenceMarkdown.split(text).length - 1, 1, "raw transcript text must appear only once");
  assert.doesNotMatch(evidenceMarkdown, /# Answer\n/);
  assert.match(evidenceMarkdown, /# Indexed historical evidence\n/);
  const grouped = new MemoryOutput();
  const sameSession = { ...turn, turn_id: "pi:historical:next", user_text: "UNIQUE_SAME_SESSION_USER", reply_text: "UNIQUE_SAME_SESSION_REPLY" };
  const otherSession = { ...turn, turn_id: "pi:other:first", session_id: "pi:other", user_text: "UNIQUE_OTHER_SESSION_USER", reply_text: "UNIQUE_OTHER_SESSION_REPLY" };
  grouped.addTranscript([sameSession, otherSession, turn, sameSession]);
  assert.deepEqual(grouped.sourceIds(), [{ id: "transcript-1", session_id: turn.session_id }, { id: "transcript-2", session_id: otherSession.session_id }]);
  const groupedResult = grouped.save("Review grouped sessions", { ...conclusion, findings: "Two sessions.[^transcript-1][^transcript-2]" });
  const groupedDirectory = join(defaultRoot, "meetings", conclusion.topic_path, groupedResult.meeting_id);
  const firstEvidence = readFileSync(join(groupedDirectory, "evidence-1.md"), "utf8");
  const secondEvidence = readFileSync(join(groupedDirectory, "evidence-2.md"), "utf8");
  for (const source of [sameSession, otherSession, turn]) {
    for (const text of [source.user_text, source.reply_text]) assert.equal(`${firstEvidence}\n${secondEvidence}`.split(text).length - 1, 1);
  }
  assert.ok(firstEvidence.includes(sameSession.user_text) && firstEvidence.includes(turn.user_text));
  assert.ok(!firstEvidence.includes(otherSession.user_text));
  assert.ok(secondEvidence.includes(otherSession.user_text) && !secondEvidence.includes(turn.user_text));
  assert.equal(readdirSync(groupedDirectory).length, 4, "one evidence file per distinct session");
  output.addTranscript([turn]);
  assert.equal(output.finalize(final).stopReason, "error", "new evidence invalidates a saved conclusion");
  output.startDiscussion();
  assert.throws(() => output.save("question", conclusion), /Finish or cancel/);
  output.cancelDiscussion();
  assert.equal(output.finalize(final).stopReason, "error", "cancelling Discussion does not discard independent fetch evidence");
  output.reset();
  assert.equal(output.finalize(final), final);
  output.addTranscript([]);
  const empty = output.save("No matches", { ...conclusion, findings: "None" });
  assert.match(empty.markdown, /# Sources\n\n\n/);
  assert.equal((output.finalize(final).content[0] as any).text, empty.markdown);

  const vault = join(home, "vault");
  mkdirSync(vault);
  const vaultKnowledge = join(vault, "pi-session-memory");
  configure({ recallMode: "normal", knowledgePath: vaultKnowledge });
  assert.equal(getSessionMemoryConfig().consultation, undefined, "a custom root does not require a consultation object");
  assert.equal(resolveKnowledgePath(), vaultKnowledge);
  const defaultMeetingsBefore = readdirSync(join(defaultRoot, "meetings"));
  output.reset(); output.addTranscript([turn]);
  const vaultRecall = output.save("Review Joule", conclusion);
  assert.equal(vaultRecall.path, join(vaultKnowledge, "meetings", conclusion.topic_path, vaultRecall.meeting_id, "minutes.md"));
  assert.equal((output.finalize(final).content[0] as any).text, readFileSync(vaultRecall.path, "utf8"));
  output.reset(); output.startDiscussion();
  const discussion = writeMeetingMinutes({ id: "discussion", owner: "main", question: "Review Joule", knowledgePath: resolveKnowledgePath(), timeoutMs: 1000,
    answers: [{ sessionId: turn.session_id, question: "Review Joule", answer: "Research only", messageIds: ["message"] }], evidence: [turn],
  }, { ...conclusion, findings: "Research only.[^consultation-1]" });
  output.complete(discussion.markdown);
  assert.equal(discussion.path, join(vaultKnowledge, "meetings", conclusion.topic_path, "discussion", "minutes.md"));
  assert.equal((output.finalize(final).content[0] as any).text, readFileSync(discussion.path, "utf8"));
  assert.equal(readConceptMetadata(discussion.markdown, discussion.path).description, conclusion.description);
  assert.ok(!existsSync(join(vault, "index.md")), "vault root notes are not plugin output");
  assert.deepEqual(readdirSync(join(defaultRoot, "meetings")), defaultMeetingsBefore, "custom storage must replace default storage, not duplicate it");
  configure({ knowledgePath: join(configRoot, "config.json") });
  output.reset(); output.addTranscript([turn]);
  assert.throws(() => output.save("question", conclusion), /not an existing file/);
  assert.equal(output.finalize(final).stopReason, "error", "storage failure must not publish a success response");
  assert.ok(!existsSync(join(home, "missing")));
  assert.deepEqual(readdirSync(join(defaultRoot, "meetings")), defaultMeetingsBefore);
  configure({ knowledgePath: "relative-root" });
  assert.throws(() => resolveKnowledgePath(), /knowledgePath must be a non-empty absolute path/);
  configure({ knowledgePath: join(configRoot, "config.json") });
  assert.throws(() => resolveKnowledgePath(), /not an existing file/);
  const aborted = { ...final, stopReason: "aborted" } as AssistantMessage;
  assert.equal(output.finalize(aborted), aborted);
  output.reset(); output.startDiscussion(); output.cancelDiscussion();
  assert.equal(output.finalize(final), final, "explicit cancellation without transcript work does not fabricate minutes");
  console.log("memory-output tests passed: exact OKF chat/file equality, both storage targets, strict errors and lifecycle isolation");
} finally { rmSync(home, { recursive: true, force: true }); }
